import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputFile = join(rootDir, 'src/data/buildVersion.ts');

const now = new Date();
const yearFull = now.getUTCFullYear();
const yearTwo = String(yearFull).slice(-2);
const month = String(now.getUTCMonth() + 1).padStart(2, '0');
const day = String(now.getUTCDate()).padStart(2, '0');
const monthDay = `${month}${day}`;

let pushNumber = '0';
try {
  const since = `${yearFull}-01-01T00:00:00Z`;
  pushNumber = execSync(`git rev-list --count --since="${since}" HEAD`, {
    cwd: rootDir,
    stdio: ['ignore', 'pipe', 'ignore'],
    encoding: 'utf8',
  }).trim();

  if (!/^\d+$/.test(pushNumber)) {
    pushNumber = '0';
  }
} catch {
  pushNumber = '0';
}

const semver = `${yearTwo}.${pushNumber}.${monthDay}`;

const fileContents = `// Auto-generated by scripts/generate-build-version.mjs\n` +
  `// Do not edit manually.\n` +
  `export const BUILD_YEAR = ${yearFull};\n` +
  `export const BUILD_SEMVER = '${semver}';\n`;

writeFileSync(outputFile, fileContents, 'utf8');
console.log(`Generated build version: ${semver}`);
